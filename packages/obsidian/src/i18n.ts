export type Language = "auto" | "en" | "zh-TW";

/** Language names, shown in their own language. */
export const LANGUAGE_NAMES: Record<Exclude<Language, "auto">, string> = { en: "English", "zh-TW": "繁體中文" };

function stringsFor(language: Language): Strings {
	if (language === "en") return en;
	if (language === "zh-TW") return zhTW;
	return getLanguage().toLowerCase().startsWith("zh") ? zhTW : en;
}

export let t: Strings = stringsFor("auto");

export function setLanguage(language: Language): void {
	t = stringsFor(language);
}

/** The CSL locale matching the language the plugin is shown in. */
export function citationLocaleForLanguage(): string {
	return t === zhTW ? "zh-TW" : "en-US";
}
